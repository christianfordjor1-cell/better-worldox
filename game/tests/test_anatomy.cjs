/* Compatibility tests, no rendering or asset manufacture. Run: node game/tests/test_anatomy.cjs */
const assert = require('node:assert/strict');
require('../src/anatomy-contract.js');
const A = global.TinyWorldAnatomy;
assert.equal(Object.keys(A.catalog.races).length,19);
assert.equal(Object.keys(A.catalog.beasts).length,17);
assert.equal(A.catalog.beasts.spider.bodyPlans[0],'arachnid');
assert.equal(A.bodyPlans.arachnid.filter(p => /^leg\d+$/.test(p)).length,8);
assert.equal(A.catalog.beasts.snake.bodyPlans[0],'serpentine');
assert(A.catalog.beasts.dragon.attachments.includes('wingLeft'));
assert.equal(A.capability('race','wolffolk').sharedHumanFit,true);
assert.equal(A.capability('race','human').anatomicalModularity,false);
const saved = Object.freeze({skin:0,hair:7,eyes:3,face:2,build:1,style:9,ornament:5,material:3});
assert.deepEqual(A.deriveAppearance('race',172,saved).values,saved);
assert.deepEqual(A.deriveAppearance('race',172,saved).derived,[]);
assert.deepEqual(A.deriveAppearance('beast',56).values,A.deriveAppearance('beast',56).values);
const base = {kind:'race',species:'human',age:'adult',bodyPlan:'biped',fit:'human/adult',cell:[144,144],anchor:[72,130],frames:A.frameOrder,status:'provisional working artwork'};
const part = {...base,id:'body',slot:'completeBody'};
assert(A.validatePart(part).ok);
assert(A.validateAssembly([part]).ok);
assert(!A.validateAssembly([part],{requireSplitAnatomy:true}).ok);
assert(!A.validatePart({...part,anchor:[72,129]}).ok);
assert(!A.validatePart({...part,frames:A.frameOrder.slice(0,-1)}).ok);
assert(!A.validatePart({...part,age:'baby'}).ok);
assert(!A.validatePart({...part,slot:'wingLeft'}).ok);
assert(!A.validatePart({...part,build:1},{build:2}).ok);
assert(!A.validatePart({...part,fit:'elf/adult'},{fit:'human/adult'}).ok);
assert(!A.validatePart(part,{species:'elf',kind:'race'}).ok);
assert(!A.validateAssembly([part,{...part,id:'second'}]).ok);
const sockets = {hip:Array.from({length:14},() => [72,80])};
const parts = A.bodyPlans.biped.map(slot => ({...base,id:slot,slot,sockets}));
assert(A.validateAssembly(parts,{requireSplitAnatomy:true}).ok);
const attached = parts.map(p => p.id === 'legLeft' ? {...p,mount:{parent:'pelvis',socket:'hip',socketOnPart:'hip'}} : p);
assert(A.validateAssembly(attached).ok);
const badSocket = attached.map(p => p.id === 'legLeft' ? {...p,sockets:{hip:Array.from({length:14},() => [73,80])}} : p);
assert(A.validateAssembly(badSocket).errors.some(e => e.code === 'socket-alignment'));
assert(!A.validateAssembly(parts.filter(p => p.slot !== 'armLeft')).ok);
assert(!A.validateAssembly([...parts,part]).ok);
console.log('Anatomy contract: 19 races, 17 beasts; identity, fit, slot and socket checks passed.');
